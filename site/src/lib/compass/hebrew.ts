/**
 * נרמול והרחבה מורפולוגית קלה לעברית עבור שכבת האחזור של „שאל את הספר”.
 *
 * חיפוש ה-Full-Text ('simple') אינו גוזר שורש, ולכן ניסוחים יומיומיים לא
 * תואמים לצורה שבספר: „בפגישות” מול „פגישות”, „לרצות” מול „רצון”, וכו'. כדי
 * להעלות recall בלי embeddings ובלי תשתית חדשה, אנחנו:
 *   1. מנרמלים תווים: הסרת ניקוד/טעמים, הסרת גרש/גרשיים, וקיפול אותיות סופיות.
 *   2. מרחיבים כל מילה לגרסה + גרסה ללא תחילית עברית נפוצה (ו/ה/ב/כ/ל/מ/ש
 *      וצירופים כמו כש/לכ/מה/שה), כשהשארית באורך ≥3.
 *
 * *אותה* פונקציה מריצה גם על תוכן הספר (בזמן הייבוא) וגם על השאלה (בזמן
 * החיפוש), כך שאין סיכון לחוסר-התאמה בין אינדוקס לשאילתה. ההרחבה *מוסיפה*
 * טוקנים בלבד — היא מעלה recall; דיוק נשמר ע"י סף-הציון ושכבת המודל.
 */

const FINALS: Record<string, string> = {
  "ך": "כ", // ך→כ
  "ם": "מ", // ם→מ
  "ן": "נ", // ן→נ
  "ף": "פ", // ף→פ
  "ץ": "צ", // ץ→צ
};

/** תחיליות עברית נפוצות (ארוכות קודם) — מנוקות מילה-מילה כשהשארית ≥3 אותיות. */
const PREFIXES = [
  "וכש", // וכש
  "כש", // כש
  "לכ", // לכ
  "מה", // מה
  "שה", // שה
  "וה", // וה
  "וב", // וב
  "ול", // ול
  "וכ", // וכ
  "ומ", // ומ
  "וש", // וש
  "ה", // ה
  "ו", // ו
  "ב", // ב
  "כ", // כ
  "ל", // ל
  "מ", // מ
  "ש", // ש
];

/** נרמול תו-רמה: הסרת ניקוד/טעמים, גרש/גרשיים ומרכאות, וקיפול אותיות סופיות. */
export function normWord(w: string): string {
  return w
    .normalize("NFC")
    .replace(/[֑-ׇ]/g, "") // ניקוד וטעמים
    .replace(/[׳״'"`]/g, "") // גרש/גרשיים/מרכאות
    .replace(/[ךםןףץ]/g, (c) => FINALS[c]);
}

/**
 * „מ” בראש מילה שאחריו נשארות בדיוק 3 אותיות היא כמעט תמיד אות-שורש או
 * תחילית-משקל (בינוני: משלם, מדבר, מחפש; שם-עצם: מקום, משפט) — לא מילת-היחס
 * „מ־”. קילוף שלה יוצר מילה אחרת לגמרי: „משלם” → „שלם”, „מדבר” → „דבר”,
 * „משהו” → „שהו”. לכן „מ” (לבדה או בסוף צירוף כמו „ומ”) נקלפת רק כשנשארות
 * לפחות 4 אותיות („מהבית”, „מהדייט” עוברות דרך „מה”).
 */
const MEM_MIN_REMAINDER = 4;

/** מרחיב מילה בודדת: הצורה המנורמלת + הצורה ללא תחילית (כשיש, ושארית ≥3). */
export function expandWord(w: string): string[] {
  const n = normWord(w);
  if (n.length < 2) return n ? [n] : [];
  const out = new Set<string>([n]);
  for (const p of PREFIXES) {
    if (!n.startsWith(p)) continue;
    const min = p.endsWith("מ") ? MEM_MIN_REMAINDER : 3;
    // תחילית שאינה עומדת בתנאי השארית אינה עוצרת את החיפוש: „ומשלם” מדלגת על
    // „ומ” ונקלפת ב„ו” בלבד ל„משלם”.
    if (n.length < p.length + min) continue;
    out.add(n.slice(p.length));
    break; // שכבת-תחילית אחת בלבד
  }
  return [...out];
}

/** מפרק טקסט לטוקנים משמעותיים (≥2 תווים), ללא נרמול/הרחבה. */
export function tokenize(text: string): string[] {
  const out: string[] = [];
  for (const raw of (text ?? "").normalize("NFC").split(/[^\p{L}\p{N}]+/u)) {
    const t = raw.trim();
    if (t.length >= 2) out.push(t);
  }
  return out;
}

/**
 * טקסט חיפוש מנורמל-ומורחב — משמש לאינדוקס (בזמן ייבוא). כל מילה הופכת
 * לצורה המנורמלת + גרסתה ללא תחילית, מופרדות ברווח כדי שה-tsvector יכיל את שתיהן.
 */
export function expandText(text: string): string {
  const toks: string[] = [];
  for (const raw of tokenize(text)) {
    for (const t of expandWord(raw)) toks.push(t);
  }
  return toks.join(" ");
}
