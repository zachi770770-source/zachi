import { describe, it, expect } from "vitest";

import { expandWord } from "@/lib/compass/hebrew";

/**
 * בדיקת-אפיון (characterization) לטווח-ההגעה המורפולוגי של שכבת האחזור.
 *
 * `hebrew.ts` מסיר **תחיליות בלבד**. הוא אינו יודע דבר על בניינים, על נטיות
 * זמן, על ריבוי, ועל שמות-פעולה — כלומר על רוב המורפולוגיה של העברית, שהיא
 * שפה תבניתית ולא רק תחילית-סיומת. התוצאה היא שגם *וריאנטים ישירים של אותו
 * שורש* אינם נפגשים, לפני שבכלל דיברנו על קרבה סמנטית.
 *
 * הבדיקה הזו אינה קובעת שהמצב תקין. היא **מקבעת את המצב הקיים** כדי ש:
 *   1. הפער יהיה גלוי ומדיד בקוד, ולא ידע שבעל-פה;
 *   2. כל שינוי עתידי בשכבת ההרחבה ייראה כאן מיד, לטוב ולרע.
 *
 * כשייכנס תיקון (הרחבת-שאילתה סמנטית, טיפול בסיומות, או אחזור וקטורי), חלק
 * מהציפיות כאן *אמורות* להתהפך — וזה בדיוק הסימן שהתיקון עשה משהו.
 */

/** האם שתי צורות נפגשות באינדוקס? שתיהן עוברות את אותה הרחבה. */
function reaches(a: string, b: string): boolean {
  const ea = new Set(expandWord(a));
  return expandWord(b).some((t) => ea.has(t));
}

describe("Hebrew morphological reach of the retrieval layer", () => {
  it("מגשר על תחיליות — וזה מה שהשכבה כן נועדה לעשות", () => {
    expect(reaches("לשלם", "משלם")).toBe(true); // שתיהן → „שלמ”
    expect(reaches("כסף", "הכסף")).toBe(true); // שתיהן → „כספ”
    expect(reaches("דייט", "בדייט")).toBe(true); // שתיהן → „דייט”
  });

  it("אינו מגשר על שם-פעולה מול שם-פועל (אותו שורש, תבנית אחרת)", () => {
    // „לשלם” → [לשלמ, שלמ] ; „תשלום” → [תשלומ]. אין טוקן משותף.
    expect(reaches("לשלם", "תשלום")).toBe(false);
    expect(reaches("נתינה", "לתת")).toBe(false);
  });

  it("אינו מגשר על נטיית זמן", () => {
    // „שילם” → [שילמ, ילמ] — התחילית שנחתכת היא ש', והשארית אינה „שלמ”.
    expect(reaches("לשלם", "שילם")).toBe(false);
  });

  it("אינו מגשר על יחיד מול רבים — גם לא של אותה מילה בדיוק", () => {
    expect(reaches("מחווה", "מחוות")).toBe(false);
    expect(reaches("דגל", "דגלים")).toBe(false);
  });

  it("אינו מגשר על מילים נרדפות או על קרבה מושגית", () => {
    // אלה אינן וריאנטים מורפולוגיים אלא מושגים — אחזור לקסיקלי לא אמור
    // לתפוס אותם, וזו בדיוק הסיבה שנדרשת שכבה נוספת כדי לענות „מי משלם”
    // מתוך קטע שמדבר על „הדדיות”.
    expect(reaches("לשלם", "חשבון")).toBe(false);
    expect(reaches("לשלם", "הדדיות")).toBe(false);
    expect(reaches("לשלם", "מחווה")).toBe(false);
    expect(reaches("כסף", "נתינה")).toBe(false);
  });
});
