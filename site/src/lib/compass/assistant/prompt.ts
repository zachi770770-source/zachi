export function isBlockedRequest(question: string): boolean {
  const q = (question ?? "").normalize("NFC");
  return BLOCK_PATTERNS.some((re) => re.test(q));
}

/** בונה את תוכן הפנייה: השאלה + הקטעים הממוספרים (המקור היחיד המותר). */
export function buildUserContent(question: string, matches: CompassMatch[]): string {
  const sources = matches
    .map((m, i) => {
      const label = m.sectionName ? `${m.chapterName}, ${m.sectionName}` : m.chapterName;
      return `מקור ${i + 1} (פרק ${m.chapterNumber}: ${label}):\n${m.content}`;
    })
    .join("\n\n");
  return [
    `שאלת המשתמש: ${question.trim()}`,
    "",
    "מקורות מהספר (השתמש רק בהם):",
    sources,
  ].join("\n");
}

/**
 * בונה את שורת הייחוס באופן דטרמיניסטי מהקטעים שנשלפו בפועל — כך המודל לא
 * יכול להמציא מקור. עד שני פרקים ראשונים (לפי סדר ההופעה). ללא מקף ארוך,
 * בהתאם לכלל האתר (אין „—”/„–” בתוכן שמוצג למשתמש).
 */
export function buildCitation(matches: CompassMatch[]): string {
  const seen = new Map<number, string>();
  for (const m of matches) {
    if (!seen.has(m.chapterNumber)) seen.set(m.chapterNumber, m.chapterName);
    if (seen.size >= 2) break;
  }
  const parts = [...seen.entries()].map(([num, name]) => `פרק ${num}: ${name}`);
  return `מבוסס על ${parts.join(" ו")}`;
}

/** ספירת מילים פשוטה (רצפי לא-רווח). */
function wordCount(s: string): number {
  const t = s.trim();
  return t ? t.split(/\s+/).length : 0;
}

/**
 * אכיפת מגבלות על הפלט: חיתוך ל-150 מילים, וקיצוץ ציטוט ישיר יחיד לכל
 * היותר 25 מילים. גם מסירים שורת „מבוסס על” אם המודל הוסיף בטעות.
 */
export function enforceAnswerLimits(text: string): string {
  let out = (text ?? "").trim();

  // הסרת שורת ייחוס עצמית (נוסיף אחת דטרמיניסטית).
  out = out
    .split("\n")
    .filter((line) => !/^\s*מבוסס\s+על/.test(line))
    .join("\n")
    .trim();

  // קיצוץ ציטוטים ישירים ארוכים מדי (בתוך מרכאות עבריות או רגילות).
  out = out.replace(/[„"“]([^„"“”]+)[”"“]/g, (whole, inner: string) => {
    const words = inner.trim().split(/\s+/);
    if (words.length <= COMPASS_LIMITS.maxQuoteWords) return whole;
    return `„${words.slice(0, COMPASS_LIMITS.maxQuoteWords).join(" ")}…”`;
  });

  // חיתוך לתקרת המילים הכוללת.
  const words = out.split(/\s+/);
  if (words.length > COMPASS_LIMITS.maxAnswerWords) {
    out = words.slice(0, COMPASS_LIMITS.maxAnswerWords).join(" ").replace(/[.,;:]$/, "") + "…";
  }
  return out.trim();
}

/** תחילית הנוסח המאושר. תמיד סירוב, בלי יוצא מן הכלל. */
const CANONICAL_REFUSAL_PREFIX = "לא מצאתי בספר בסיס מספיק";

/**
 * חלון הפתיחה שבו מחפשים ניסוח-סירוב. סירוב אמיתי תמיד פותח את התשובה; מילים
 * דומות באמצע תשובה ארוכה אינן סירוב.
 */
const REFUSAL_WINDOW_CHARS = 160;

/**
 * ניסוחי-סירוב מוכרים מעבר לנוסח המאושר.
 *
 * ההנחיה מבקשת מהמודל להחזיר את הנוסח המאושר *במדויק*, אבל הסתמכות על כך
 * הייתה תלות בהתנהגות ספק: תשובה כמו „הקטעים שקיבלתי אינם עוסקים בכך” או
 * „הספר אינו עוסק בנושא הזה” עברה כ-`answered`, וקיבלה שורת „מבוסס על פרק
 * N” — כלומר סירוב שהולבש כתשובה מצוטטת מהספר. buildCitation נבנה מהקטעים
 * שנשלפו ואינו מסתכל כלל בטקסט המודל, ולכן הוא אינו יכול להגן על עצמו.
 *
 * הרשימה מכוונת ומצומצמת: צירוף של „אין/לא” עם *נושא סגור* (הקטעים / המקורות
 * / הספר / השאלה), לא מילת-שלילה כללית. כך „אין פה תשובה אחת נכונה” — משפט
 * לגיטימי לגמרי בספר הזה — אינו נתפס כסירוב.
 */
const REFUSAL_PATTERNS: RegExp[] = [
  // „לא מצאתי …” על מקור סגור.
  /לא\s+מצאתי\s+(ב(ספר|קטעים|מקורות)|במה\s+שקיבלתי)/,
  /לא\s+מצאתי\s+(מידע|התייחסות|בסיס|תשובה|משהו)/,
  // „הקטעים / המקורות … אינם / לא …”
  /(הקטעים|המקורות|הקטעים\s+שקיבלתי|המקורות\s+שקיבלתי)\s+\S{0,12}\s*(אינם|לא)\s+(עוסקים|מכילים|מתייחסים|נוגעים|כוללים|מספקים)/,
  /(אין|לא\s+נמצא)\s+ב(קטעים|מקורות|ספר)\s+\S{0,12}\s*(בסיס|מידע|התייחסות|תשובה)/,
  // „הספר אינו / לא עוסק …”
  /ה?ספר\s+(אינו|איננו|לא)\s+(עוסק|מתייחס|מדבר|נוגע|מכיל|עונה)/,
  // „אין לי בסיס / אין לי מספיק …”
  /אין\s+לי\s+(בסיס|מספיק|מידע|התייחסות)/,
  // „השאלה … חורגת / אינה בתחום הספר”
  /(השאלה|הנושא)\s+\S{0,12}\s*(חורג(ת)?|אינ(ה|ו)\s+(בתחום|קשור(ה)?|נוגע(ת)?))/,
  // גלישה לאנגלית (נדיר, אך אינו אמור להיספר כתשובה מצוטטת).
  /^(i (don'?t|do not|cannot|can'?t)|the (provided )?(sources|excerpts|passages))/i,
];

/**
 * המשך מנוגד ומהותי אחרי הסתייגות („… אבל העיקרון בספר אומר ש…”) הוא תשובה,
 * לא סירוב. אינו חל על הנוסח המאושר, כדי שגרסה מורחבת שלו לא תחמוק מהשער.
 */
const CONTRASTIVE_CONTINUATION = /(^|\s)(אבל|אך|עם\s+זאת|יחד\s+עם\s+זאת|למרות\s+זאת)(\s|,)/;
const CONTRASTIVE_MIN_WORDS = 20;

/**
 * האם התשובה שהמודל החזיר היא סירוב („אין בסיס מספיק”)?
 *
 * דטרמיניסטי לחלוטין, בלי קריאה נוספת למודל. כישלון-הזיהוי היחיד שנשאר הוא
 * בכיוון השמרני: ניסוח סירוב חריג שאינו ברשימה יטופל כתשובה. לכן הבדיקה
 * מלווה במבחני ספק-מדומה שמכסים את הניסוחים שנצפו בפועל.
 */
export function isModelRefusal(text: string): boolean {
  const t = (text ?? "").replace(/[„”"“]/g, "").trim();
  if (!t) return false;
  if (t.startsWith(CANONICAL_REFUSAL_PREFIX)) return true;

  const head = t.slice(0, REFUSAL_WINDOW_CHARS);
  if (!REFUSAL_PATTERNS.some((re) => re.test(head))) return false;

  // הסתייגות שאחריה באמת מגיעה תשובה מהותית אינה סירוב.
  const turn = t.search(CONTRASTIVE_CONTINUATION);
  if (turn !== -1 && wordCount(t.slice(turn)) >= CONTRASTIVE_MIN_WORDS) return false;
  return true;
}

/**
 * חילוץ דטרמיניסטי של שורת „על מה שווה לשים לב עכשיו” מפלט המודל, אם קיימת.
 * מפצל בתווית האחרונה: מה שלפניה = גוף התשובה, מה שאחריה (עד סוף השורה) =
 * שורת תשומת-הלב. אינו ממציא דבר: אם התווית אינה קיימת, מחזיר את הטקסט כגוף
 * ו-focus=undefined. מחיל שמירות: משפט אחד, גזירה ל-30 מילים לכל היותר,
 * ודחיית ערך ריק או נוסח-הסירוב. יש להריץ *לפני* enforceAnswerLimits כדי
 * שתקרת-המילים של הגוף לא „תבלע” את השורה.
 */
export function extractFocus(text: string): { body: string; focus?: string } {
  const raw = (text ?? "").trim();
  if (!raw) return { body: "" };
  const idx = raw.lastIndexOf(FOCUS_LABEL);
  if (idx === -1) return { body: raw };

  const body = raw.slice(0, idx).trim();
  // מסירים את התווית ומפריד „:” אופציונלי, לוקחים שורה אחת בלבד.
  let focus = raw
    .slice(idx + FOCUS_LABEL.length)
    .replace(/^\s*[:：]?\s*/, "")
    .split("\n")[0]
    .trim();

  const w = focus.split(/\s+/).filter(Boolean);
  if (w.length > 30) focus = w.slice(0, 30).join(" ");

  // ערך לא תקין (ריק / נוסח סירוב) → אין שורת תשומת-לב; שומרים על הגוף.
  if (!focus || isModelRefusal(focus)) return { body: body || raw };
  // אם אחרי החיתוך אין גוף (המודל החזיר רק את השורה) → מתייחסים לכל הטקסט כגוף.
  if (!body) return { body: raw };
  return { body, focus };
}

