/** התווית המדויקת של שאלת-ההמשך. משמשת בהנחיה ובחילוץ הדטרמיניסטי. */
export const FOLLOWUP_LABEL = "שאלת המשך";

/**
 * מרקר-בקרה שהמודל פולט *רק* כשהתור הזה מסר תובנה אמיתית ומבוססת-ספר שאפשר
 * לעשות איתה משהו (לא אמפתיה גנרית, לא רק הסתייגות, ולעולם לא בסירוב/בטיחות).
 * ASCII, כדי שלא יופיע בטעות בעברית, ומאפשר לחשב `valueDelivered` דטרמיניסטית.
 * אינו נחשף למשתמש. זה, ורק זה, פותח את גשר-הרכישה בעמוד הבית.
 */
export const COMPASS_VALUE_MARKER = "[[VALUE]]";

/**
 * חילוץ דטרמיניסטי של מרקר-הערך מפלט המודל: מסיר כל מופע של „[[VALUE]]"
 * (המרקר לעולם אינו טקסט עברי לגיטימי) ומחזיר האם היה נוכח. יש להריץ *לפני*
 * חילוץ שאלת-ההמשך/הפוקוס, כדי שהמרקר לא ייבלע כחלק מהגוף או מהשורה הנגררת.
 * הנוכחות לבדה אינה מספיקה ל-`valueDelivered`: השכבה שמעל דורשת גם status
 * "answered" (אחזור-מוצלח + ציטוט אמיתי), כך שסירוב שנפלט בטעות עם מרקר לעולם
 * אינו נספר כערך.
 */
export function extractValueMarker(text: string): {
  body: string;
  valueDelivered: boolean;
} {
  const raw = text ?? "";
  if (!raw.includes(COMPASS_VALUE_MARKER)) return { body: raw, valueDelivered: false };
  const body = raw
    .split(COMPASS_VALUE_MARKER)
    .join("")
    .replace(/[ \t]+$/gm, "")
    .trim();
  return { body, valueDelivered: true };
}

