/**
 * המשך מנוגד ומהותי אחרי הסתייגות („… אבל העיקרון בספר אומר ש…”) הוא תשובה,
 * לא סירוב. זהו בדיוק המבנה של מענה מעוגן-על-עיקרון-סמוך: „הספר לא קובע X, אבל
 * הוא כן מזמין להסתכל על…”. הרשימה כוללת גם מפני-ניגוד וגם מפני-חיוב („הספר כן
 * מציע…”, „מה שכן עולה…”), כדי שמענה כזה לא ייבלע כסירוב גם כשאינו פותח ב„אבל”.
 */
const CONTRASTIVE_CONTINUATION =
  /(^|\s)(אבל|אך|עם\s+זאת|יחד\s+עם\s+זאת|למרות\s+זאת|ובכל\s+זאת|בכל\s+זאת|לעומת\s+זאת|מצד\s+שני|מה\s+שכן)(\s|,)/;
/** מפנה חיובי: „הספר כן מציע/מזמין…”, „הוא כן עוסק…”, „כן עולה מהקטעים…”. */
const AFFIRMATIVE_PIVOT =
  /(^|\s)(ה?ספר|הוא|זה)\s+כן\s+(מציע|מזמין|עוסק|מדבר|נוגע|מראה|מזכיר|מדגיש|מצביע|עולה)|(^|\s)(מה\s+ש)?כן\s+(מציע|מזמין|עולה|מראה|מזכיר|מדגיש)/;
const CONTRASTIVE_MIN_WORDS = 20;

/**
 * האם התשובה שהמודל החזיר היא סירוב („אין בסיס מספיק”)?
 *
 * דטרמיניסטי לחלוטין, בלי קריאה נוספת למודל. כישלון-הזיהוי היחיד שנשאר הוא
 * בכיוון השמרני: ניסוח סירוב חריג שאינו ברשימה יטופל כתשובה. לכן הבדיקה
 * מלווה במבחני ספק-מדומה שמכסים את הניסוחים שנצפו בפועל.
 */
export function isModelRefusal(text: string): boolean {
  const t = (text ?? "").replace(/[„”"“]/g, "").trim();
  if (!t) return false;
  if (t.startsWith(CANONICAL_REFUSAL_PREFIX)) return true;
  // הנוסח האנושי המאושר נשאר סירוב תמיד, גם אם הודבק לו „המשך מנוגד” — כדי שלא
  // יולבש כתשובה מצוטטת. נבדק לפני שער-המפנה.
  if (APPROVED_REFUSAL && t.startsWith(APPROVED_REFUSAL)) return true;

  const head = t.slice(0, REFUSAL_WINDOW_CHARS);
  if (!REFUSAL_PATTERNS.some((re) => re.test(head))) return false;

  // הסתייגות שאחריה באמת מגיע מסגור-מחדש מהותי (מפנה-ניגוד או מפנה-חיוב, ואז
  // תוכן ממשי) היא תשובה מעוגנת על עיקרון סמוך, לא סירוב.
  const pivots = [t.search(CONTRASTIVE_CONTINUATION), t.search(AFFIRMATIVE_PIVOT)].filter(
    (i) => i !== -1,
  );
  if (pivots.length) {
    const turn = Math.min(...pivots);
    if (wordCount(t.slice(turn)) >= CONTRASTIVE_MIN_WORDS) return false;
  }
  return true;
}

/**
 * מפענח את סימון „אין בסיס כלל”. אם פלט המודל פותח ב-COMPASS_NO_BASIS_SENTINEL,
 * זהו סירוב אמיתי מפורש: מחזיר את משפט-הסירוב האנושי והספציפי שאחריו (שורה אחת,
 * עד 40 מילים) — או את הנוסח האנושי הקבוע אם המודל לא צירף משפט תקין. מחזיר null
 * כשאין סימון (כלומר יש תשובה/מסגור-מחדש רגילים, גם אם הם פותחים ב„הספר לא קובע…”).
 * דטרמיניסטי לחלוטין, בלי קריאה נוספת למודל.
 */
export function parseNoBasisMarker(text: string): { text: string } | null {
  const t = (text ?? "").trim();
  if (!t.startsWith(COMPASS_NO_BASIS_SENTINEL)) return null;
  let rest = t
    .slice(COMPASS_NO_BASIS_SENTINEL.length)
    .replace(/^[\s:：.,\-–—]+/, "")
    .trim();
  rest = (rest.split("\n").map((s) => s.trim()).filter(Boolean)[0] ?? "").trim();
  const words = rest.split(/\s+/).filter(Boolean);
  if (words.length > 40) rest = words.slice(0, 40).join(" ");
  // בלי משפט תקין (או אם נותר סימון בטקסט) → הנוסח האנושי הקבוע.
  if (!rest || rest.includes(COMPASS_NO_BASIS_SENTINEL)) {
    return { text: COMPASS_INSUFFICIENT_ANSWER };
  }
  return { text: rest };
}

/**
 * חילוץ דטרמיניסטי של שורת „על מה שווה לשים לב עכשיו” מפלט המודל, אם קיימת.
 * מפצל בתווית האחרונה: מה שלפניה = גוף התשובה, מה שאחריה (עד סוף השורה) =
 * שורת תשומת-הלב. אינו ממציא דבר: אם התווית אינה קיימת, מחזיר את הטקסט כגוף
 * ו-focus=undefined. מחיל שמירות: משפט אחד, גזירה ל-30 מילים לכל היותר,
 * ודחיית ערך ריק או נוסח-הסירוב. יש להריץ *לפני* enforceAnswerLimits כדי
 * שתקרת-המילים של הגוף לא „תבלע” את השורה.
 */
export function extractFocus(text: string): { body: string; focus?: string } {
  const raw = (text ?? "").trim();
  if (!raw) return { body: "" };
  const idx = raw.lastIndexOf(FOCUS_LABEL);
  if (idx === -1) return { body: raw };

  const body = raw.slice(0, idx).trim();
  // מסירים את התווית ומפריד „:” אופציונלי, לוקחים שורה אחת בלבד.
  let focus = raw
    .slice(idx + FOCUS_LABEL.length)
    .replace(/^\s*[:：]?\s*/, "")
    .split("\n")[0]
    .trim();

  const w = focus.split(/\s+/).filter(Boolean);
  if (w.length > 30) focus = w.slice(0, 30).join(" ");

  // ערך לא תקין (ריק / נוסח סירוב) → אין שורת תשומת-לב; שומרים על הגוף.
  if (!focus || isModelRefusal(focus)) return { body: body || raw };
  // אם אחרי החיתוך אין גוף (המודל החזיר רק את השורה) → מתייחסים לכל הטקסט כגוף.
  if (!body) return { body: raw };
  return { body, focus };
}

