/** בונה תשובת-בטיחות אחידה מתוצאת הסיווג. ללא ציטוט וללא שורת-פוקוס. */
export function buildSafetyAnswer(result: CompassSafetyResult): Extract<CompassAnswer, { status: "safety" }> {
  const key = result.responseKey ?? "crisis";
  return {
    status: "safety",
    category: result.category ?? "crisis",
    severity: result.severity ?? "high",
    text: SAFETY_COPY[key],
  };
}
