/**
 * איזה משני עמודי-האב שייך לשלב שהקורא נמצא בו.
 *
 * ── הבעיה שזה פותר ───────────────────────────────────────────────────────
 * כל מדריך, כל עמוד-תחנה וכל עמוד-מסע נשא בתחתיתו את אותו קישור בדיוק:
 * „התמונה הרחבה: מהי אהבה ואיך היא נבנית” → /love. גם מדריך על דייט ראשון,
 * גם מדריך על ריבים חוזרים. התוצאה נמדדה בגרף-הקישורים של האתר:
 *
 *     /love    39 קישורים נכנסים
 *     /dating   5 קישורים נכנסים
 *
 * כלומר עמוד-האב של „דייטים / היכרות” — הצד שהספר קרוי על שמו, והמונח שיש לו
 * הכי הרבה חיפושים — היה כמעט יתום בתוך האתר של עצמו. זו לא הטיה טכנית: היא
 * גם מבלבלת קורא שסיים מדריך על דייט ראשון ומקבל הצעה לקרוא על בניית אהבה
 * ארוכת-טווח, במקום על השלב שבו הוא באמת נמצא.
 *
 * ── הכלל ─────────────────────────────────────────────────────────────────
 * המסע הוא דייטים → היכרות → קשר → זוגיות → אהבה. הקישור הרוחבי מפנה אל
 * עמוד-האב שמכסה את *השלב הנוכחי*, לא אל אותו עמוד תמיד:
 *
 *   • שלב החיפוש (לפני קשר, חזרה לדייטים, וכל מדריך שתלוי בהם) → /dating
 *   • שלב הבנייה (תחילת קשר, קשר קיים, אחרי פרידה)             → /love
 *
 * „אחרי פרידה” הולך אל /love במכוון: השאלה שם אינה איך לחפש אלא מה באמת היה
 * שם ומה מחזיק קשר — וזו השאלה של /love.
 *
 * עמוד שכבר *יושב* על אחד מעמודי-האב מקבל את השני: מדריך שה-hub שלו הוא
 * /dating מקבל את /love, וכך נוצר קישור הדדי במקום עצמי.
 */

export interface PillarLink {
  href: "/dating" | "/love";
  /** תווית עריכתית — מתארת את מה שיש בעמוד היעד, לא צירוף מילות-חיפוש. */
  label: string;
}

const DATING: PillarLink = {
  href: "/dating",
  label: "התמונה הרחבה: מה באמת קורה בשלב הדייטים",
};

const LOVE: PillarLink = {
  href: "/love",
  label: "התמונה הרחבה: מהי אהבה ואיך היא נבנית",
};

/**
 * שלבי-המסע ששייכים לצד החיפוש. כל שאר השלבים שייכים לצד הבנייה, ולכן
 * הרשימה הזו היא הדבר היחיד שצריך לעדכן אם נוספת תחנה חדשה.
 */
const SEARCH_STAGES = new Set(["before-relationship", "starting-again", "dating"]);

/**
 * @param stage מזהה השלב — slug של תחנה (`before-relationship`), או הנתיב של
 *   ה-hub שאליו המדריך משויך (`/before-relationship`). שתי הצורות מתקבלות כדי
 *   שקוראים לא יצטרכו לנרמל בכל אתר-קריאה.
 */
export function pillarForStage(stage: string): PillarLink {
  const slug = stage.replace(/^\//, "");
  // עמוד שכבר יושב על /dating מקבל את עמוד-האב השני, ולא קישור אל עצמו.
  if (slug === "dating") return LOVE;
  if (slug === "love") return DATING;
  return SEARCH_STAGES.has(slug) ? DATING : LOVE;
}
