/**
 * כלי בודד מהספר. `id`, `name` ו-`description` הם התוכן המאושר הקיים.
 *
 * שדות ההעשרה (`whenToUse`/`howItWorks`/`example`/`exercise`/`quote`) הם
 * *ציטוט ישיר מכתב-היד המלא של „מדייטים לאהבה”* — לא נוסח מחדש ולא הומצא.
 * `source` הוא הפרק שממנו נלקח הטקסט (לתיעוד ולדוח; אינו מוצג למבקר). כלי
 * שאין לו מקור מאומת בכתב-היד נשאר בלי שדות ההעשרה — לא ממציאים לו תוכן.
 * לכתב-היד (docx) אין מספרי-עמוד יציבים (פורמט זורם), ולכן הציטוט מיוחס לפרק
 * לפי מפתח-הכלים של הספר עצמו („איפה נמצא הכלי שאני צריך?”).
 *
 * `audioSrc` + `audioTranscript` הם *אופציונליים* ותמיד ריקים כאן: אין להוסיף
 * הקלטה בלי קובץ שמע אמיתי ומאושר *וגם* תמלול מלא. הרכיב (ToolsBento) מציג נגן
 * אך ורק כששני השדות מלאים — אחרת אין נגן, אין שטח ריק ואין קובץ דמה/קול AI.
 * הנגן אינו מתנגן אוטומטית ואינו טוען את הקובץ עד שהכרטיס נפתח והמשתמש מנגן.
 */
export type ToolItem = {
  id: string;
  name: string;
  description: string;
  /** „מתי זה מתאים” — ציטוט מהספר. */
  whenToUse?: string;
  /** „איך זה עובד” — ציטוט מהספר. */
  howItWorks?: string;
  /** דוגמה קצרה — ציטוט מהספר. */
  example?: string;
  /** תרגיל/שאלה קצר/ה (עד דקה) — ציטוט מהספר. */
  exercise?: string;
  /** ציטוט קצר לקחת — מהספר. */
  quote?: string;
  /** הפרק שממנו נלקחו הציטוטים (תיעוד/דוח; לא מוצג למבקר). */
  source?: string;
  /** נתיב תחת /public לקובץ שמע מאושר. ריק = אין נגן. */
  audioSrc?: string;
  /** תמלול מלא ונגיש של ההקלטה. חובה יחד עם audioSrc — אחרת אין נגן. */
  audioTranscript?: string;
};

