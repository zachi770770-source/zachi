/**
 * ארבעת „שערי-המסע” של „מדייטים לאהבה” — ארבע חוויות כניסה *שונות* לספר, לא
 * עמודי-SEO ולא כרטיסי-ניווט מוגדלים. כל עמוד נכתב לשפת-המצב שלו: הקורא נכנס,
 * מרגיש שמבינים אותו, מגלה משהו על עצמו/על הקשר, מסתקרן — ואז רוצה לקרוא את
 * הקטע מהספר.
 *
 * כל ה-copy כאן הוא editorial של האתר (מותר לכתוב חדש). הקטע מהספר עצמו אינו
 * נכתב כאן: הוא מגיע מ-`/preview?tool=&station=` (תוכן מאושר של הכלי). אין להמציא
 * ציטוטים/פרקים/מחקר/המלצות ואין להבטיח תוצאה טיפולית. „אחרי פרידה” משתמש
 * ב-personaExamples.breakup של הכלי (מיושם ב-Preview, אושר ותוקן).
 *
 * המטרה: Recognition + insight שפותחים סקרנות — לא „מאמר שלם” שסוגר את הנושא.
 * `variant` נותן לכל מסלול קצב/יישור שונים בעדינות — בלי לשבור את שפת המותג.
 */

export type JourneyId =
  | "before-relationship"
  | "building-relationship"
  | "inside-relationship"
  | "after-breakup";

export type JourneyVariant = "clarity" | "movement" | "depth" | "space";

export interface JourneyDepthPoint {
  title: string;
  line: string;
}

export interface JourneyPage {
  id: JourneyId;
  variant: JourneyVariant;
  eyebrow: string;
  h1: string;
  intro: string;
  /** שורת מצב-רוח — הטון הרגשי, כבר במסך הראשון. */
  moodLine: string;

  /** B. „מה באמת קורה בשלב הזה” — כותרת + 3–4 פסקאות שיקוף (לא עצות). */
  whatsHappeningHeading: string;
  whatsHappening: string[];

  /** C. שלוש נקודות עומק — כותרת + משפט הסבר לכל אחת. הכותרת נושאת את נושא
   *  החיפוש של העמוד (SEO), במקום ניסוח גנרי אחיד לכל התחנות. */
  depthHeading: string;
  depthPoints: [JourneyDepthPoint, JourneyDepthPoint, JourneyDepthPoint];

  /** D. Moment of recognition — משפט גדול לעצור עליו. */
  pullQuote: string;

  /** „שאלת מראה” — שאלה אחת editorial לעצור עליה. לא form, לא input, לא כפתור. */
  mirrorQuestion: string;

  /** E. „מה הספר יעזור לכם לראות” — 2–3 תובנות ממוקדות (בלי הבטחת תוצאה). */
  bookHelpsHeading: string;
  bookHelps: string[];

  /** F. משפט-מעבר לטעימה — „פתיחת לולאה”, ממסגר למה הקטע מתאים בדיוק כאן. */
  sampleLead: string;
  /** G. תווית הפעולה הראשית — הטעימה מהספר. */
  samplePrimaryLabel: string;
  /** Early CTA — נקודת כניסה מוקדמת ושקטה לטעימה (מיד אחרי ה-reflection הראשון,
      לקורא שכבר השתכנע). אותה טעימה מותאמת — לא /preview כללי. */
  earlyCtaLabel: string;

  /** הכלי המאושר + ה-station ל-Preview, והתחנה המקבילה ב„שאל את הספר”. */
  sampleTool: string;
  sampleStation: JourneyId;
  compassStation: AskStationId;

  /**
   * override מפורש לקישור-המושג ההקשרי („המושג מהספר”), כ-slug של /method/*.
   * ברירת המחדל: הקישור נגזר מ-sampleTool (המושג של כלי הטעימה). אבל לפעמים
   * המושג שממסגר את *הבחירה* בשלב הזה אינו הכלי של הטעימה — ואז מציינים אותו
   * כאן במפורש, בלי לגעת בטעימה. „לפני קשר”: „קו אדום מול גמישות” (core-values)
   * הוא המושג שעונה ישירות על „למה אני פוסל/ת מהר, ומה אני באמת צריך/ה” —
   * בעוד הטעימה נשארת „עובדה, סיפור, פעולה”.
   */
  featuredMethodSlug?: string;

  /** I. Next step — שונה לפי המסלול (רך). */
  nextStep: { prompt: string; href: string; label: string };
}

