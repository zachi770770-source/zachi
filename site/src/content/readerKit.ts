export type ReaderResourceKind = "tool" | "guide" | "workbook" | "series";

export interface ReaderResource {
  /** מזהה יציב (לאנליטיקה `reader_resource_opened`). */
  id: string;
  title: string;
  /** משפט-מסגור קצר, נגזר מההגדרה הקיימת של הכלי/המדריך — לא עיקרון חדש. */
  summary: string;
  /** יעד פנימי קיים (עמוד-מושג / מדריך / מסלול-הערכה). */
  href: string;
  kind: ReaderResourceKind;
}

export interface ReaderNeedGroup {
  /** הצורך שהקבוצה עונה עליו — הארגון של הערכה הוא לפי צורך, לא רשימת קבצים. */
  id: string;
  need: string;
  resources: ReaderResource[];
}

