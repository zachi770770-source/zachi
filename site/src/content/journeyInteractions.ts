/**
 * „פעולה קטנה אחת” לכל תחנה — לא שאלון ולא כלי חדש: רגע קצר שבו המבקר/ת *עושה*
 * משהו קטן שמתאים לשלב (מסמן/ת בחירה), ומיד נחשף שיקוף קצר. מקור-אמת יחיד לכל
 * חמש התחנות; רכיב אחד (`JourneyInteraction`) מרנדר את כולן לפי ה-data כאן.
 *
 * כל התוכן נשען על מושגים שכבר קיימים בספר, על ששת הכלים הקנוניים, ועל copy
 * עריכתי קיים/מאושר באתר. אין המצאת כלי, אבחון, תווית פסיכולוגית, ציטוט מהספר,
 * או הבטחת טיפול.
 *
 * המימוש הוא CSS טהור (`:has(input:checked)`), ולכן ה-state הוא ephemeral לחלוטין:
 * אין localStorage, cookies או DB, ושום דבר אינו נשמר אחרי העמוד. כל בחירה היא
 * radio נטיבי בקבוצה — מקלדת וקורא-מסך עובדים, וה-state נמסר גם בטקסט (השיקוף
 * שנחשף), לא בצבע בלבד.
 */

/** בחירה יחידה בתוך שאלה — התווית שהמשתמש/ת מסמן/ת, והשיקוף שנחשף בעקבותיה. */
export interface JourneyInteractionChoice {
  /** התווית הנבחרת (הכפתור). */
  label: string;
  /** תג-מצב קצר (אופציונלי) — נמסר כטקסט, לא כצבע. */
  tag?: string;
  /** השיקוף הקצר שנחשף אחרי הבחירה — משפט אחד, לא הוראה אלגוריתמית. */
  reflection: string;
}

/** „שאלה” אחת — מה מסמנים עליו, ומבחר הבחירות (radiogroup נטיבי אחד). */
export interface JourneyInteractionItem {
  prompt: string;
  choices: JourneyInteractionChoice[];
}

export interface JourneyInteraction {
  eyebrow: string;
  title: string;
  intro: string;
  /** הערת-מסגור קצרה (אופציונלי) — לרוב שלוש-נקודות ההסתכלות של השלב. */
  note?: string;
  items: JourneyInteractionItem[];
  /** שורת-סגירה — מחזירה אל התובנה (לא ניקוד, לא „נכון/לא-נכון”). */
  closing: string;
  /** מושג-ספר קנוני מלווה (אופציונלי) — slug של אחד מששת הכלים בלבד. */
  methodSlug?: string;
}

