/**
 * „שאל את הספר” — מקור-אמת יחיד למנוע ההכוונה האישי, הסגור והדטרמיניסטי.
 *
 * זה *אינו* צ׳אט/AI ואין תיבת-טקסט חופשית: כל האפשרויות סגורות, המיפוי
 * דטרמיניסטי בצד-הלקוח, ואין קריאה ל-API חיצוני. אין אבחון, טיפול או „תשובה
 * נכונה”. המנוע מכוון אל התוכן והכלים הקיימים בספר.
 *
 * שלוש שכבות:
 *   1) תחנה  — איפה האדם עכשיו: חיפוש ודייטים · בניית קשר · קשר קיים · אחרי פרידה.
 *   2) דילמה — מה מעסיק אותו כרגע (רשימה קצרה ורלוונטית לכל תחנה).
 *   3) הקשר  — שאלה משלימה *אחת בלבד*, ורק כשהיא באמת משנה את התשובה (פרק ב'/
 *      ילדים/גרוש-ה/קצב/בטיחות).
 *
 * „אחרי פרידה” היא תחנת-מעבר: אין לדחוף אוטומטית לחזרה לדייטים או לקשר — התוצאה
 * יכולה גם להציע לעצור, לעבד ולהבין. „פרק ב'” אינו תחנה נפרדת אלא שכבת התאמה
 * בתוך התחנה והדילמה. שכבת בטיחות דורסת את התוצאה הרגילה במצבי סכנה/מצוקה.
 *
 * ⚠️ הרבה מטקסטי-הדילמות הם *טיוטה ראשונית* נאמנה לקול הקיים — טעונים אישור-תוכן
 * של צחי (מסומן בדוח הסיום). הכלים והמיצוב נשענים על התוכן המאושר הקיים.
 */

export type AskStationId = "dating" | "building" | "existing" | "after-breakup";
export type PageStationId =
  | "before-relationship"
  | "starting-again"
  | "inside-relationship";

/** מבנה-תשובה אחיד לכל דילמה (8 חלקים). */
export interface AskAnswer {
  /** 1. שיקוף קצר — אנושי, בלי קביעה מוחלטת. */
  reflection: string;
  /** 2. ההבחנה המרכזית — הרעיון מהספר שמאפשר להסתכל אחרת. */
  distinction: string;
  /** 3. מה כדאי לבדוק — 2–3 שאלות קצרות לבירור עצמי. */
  checks: string[];
  /** 4. הכלי המתאים — מזהה כלי קיים מהספר (כשיש התאמה). */
  toolId?: string;
  /** 5. פעולה קטנה להיום. */
  action: string;
  /** 6. מה לא כדאי להסיק מהר מדי. */
  avoid: string;
  /** 7. קטע מתאים מהספר — עמוד-התחנה לקישור /preview. */
  sampleStation: PageStationId;
}

export interface AskContextOption {
  id: string;
  label: string;
  /** התאמת-תוכן שנוספת/דורסת כשנבחרה (למשל פרק ב'). */
  adapt?: { note?: string; action?: string; checks?: string[] };
  /** אם true — מפעילה ניתוב-בטיחות (דורס את התוצאה הרגילה). */
  safety?: boolean;
}

/** שאלת-הקשר משלימה אחת — מוצגת רק לדילמות שבהן ההקשר משנה את התשובה. */
export interface AskContext {
  question: string;
  options: AskContextOption[];
}

export interface Dilemma {
  id: string;
  station: AskStationId;
  /** ניסוח הדילמה (מתוך 19 הבסיס). */
  label: string;
  answer: AskAnswer;
  context?: AskContext;
}

