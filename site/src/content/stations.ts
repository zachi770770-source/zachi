/**
 * תוכן שלוש התחנות: „לפני קשר”, „מתחילים מחדש” ו„בתוך קשר”.
 *
 * זהו מקור האמת היחיד לתוכן שלושת דפי התחנות. כל הטקסטים כאן נגזרים
 * מהמיצוב ומהתוכן שכבר אושרו (src/content/book.ts, src/content/author.ts):
 * ספר אחד, מסע אחד, ושלוש נקודות פתיחה. אין כאן זהות, תארים או הבטחות
 * חדשות. כדי לערוך כותרת, פסקה, פרק, ציטוט או שאלה — עורכים כאן בלבד;
 * הלוגיקה (CTA לפי מצב המכירה, ניווט, סכימות) נשארת ברכיבים.
 *
 * מזהה התחנה (`id`) הוא גם ה-slug של הדף: /before-relationship וכו'.
 */

export interface StationChapter {
  /** שם הפרק כפי שהוא מופיע בתוכן העניינים (src/content/book.ts). */
  title: string;
  /** למה הפרק רלוונטי לתחנה הזו — נוסח שונה בכל תחנה, ללא כפילות. */
  note: string;
}

export interface Station {
  /** משמש גם כ-slug של הדף וגם כמפתח ב-URL. */
  id: "before-relationship" | "starting-again" | "inside-relationship";
  /** תווית קצרה לניווט, לכרטיסים ולקישורים בין התחנות. */
  navLabel: string;
  /** כותרת H1 של הדף. */
  h1: string;
  /** משפט פתיחה קצר מתחת ל-H1. */
  lead: string;
  /** כותרת SEO ייחודית (<title>). */
  metaTitle: string;
  /** meta description ייחודי. */
  metaDescription: string;
  /** תיאור הקושי — אנושי, לא שיפוטי. */
  difficulty: { title: string; paragraphs: string[] };
  /** מה הספר מציע בתחנה הזו. */
  offer: { title: string; paragraphs: string[] };
  /** משפט מודגש אחד (אופציונלי) — מסר מרכזי לתחנה. */
  highlight?: string;
  /** הפרקים הרלוונטיים מתוך הספר (מתוך תוכן העניינים). */
  chapters: StationChapter[];
  /** קטע קצר ומאושר — לקוח מטקסטים שכבר אושרו; שונה בכל תחנה. */
  excerpt: string;
  /** שאלה אחת למחשבה. */
  question: string;
}

