import type { AskStationId } from "@/content/askRoute";

/**
 * עמודי-מושג (/method/*) — ההגדרה הקנונית של הכלים המקוריים של „מדייטים לאהבה”.
 * כל הגדרה נגזרת אך ורק מהמקור הקיים (src/content/book.ts, tools) — אין המצאת
 * מושגים או הגדרות. עמוד-המושג הוא ה„שם-העצם” (מהו הכלי); עמודי /guide/* הם
 * ה„פועל” (איך מיישמים אותו במצב מסוים), ומקושרים הדדית. כל עמוד נושא canonical
 * עצמי, וסכימת DefinedTerm המחוברת לישות הספר.
 *
 * חשוב: משתמשים רק בכלים המאומתים בספר. שמות שלא קיימים במקור (למשל „מפת הערכים”,
 * „שאלת הדגלים”, „הסכם ההתחלה”, „הסכמה רגשית”) — אינם בשימוש כאן.
 */

export interface MethodSection {
  heading: string;
  paragraphs: string[];
}

export interface MethodLink {
  href: string;
  label: string;
  sub?: string;
}

/** פריט ב„מפת הסינון” — דוגמה קונקרטית וצדה (קו אדום / גמישות) + נימוק קצר. */
export interface FilterMapItem {
  label: string;
  side: "line" | "flex";
  reason: string;
}

/**
 * „מפת הסינון” האינטראקטיבית של „קו אדום מול גמישות” — אופציונלית, לעמוד-מושג
 * שהרעיון שלו הוא המיון עצמו. הדוגמאות והצדדים נגזרים מהתוכן הקיים של המושג
 * (שתי הטעויות ושני הטורים); הנימוקים הם משפט-גישור קצר לפי „העיקרון שמנחה”.
 */
export interface FilterMap {
  eyebrow: string;
  title: string;
  intro: string;
  lineLabel: string;
  flexLabel: string;
  items: FilterMapItem[];
  principle: string;
  /** שורת-רפלקציה סוגרת — מפנה את הזרקור פנימה (לא ניקוד, לא נכון/לא-נכון). */
  closing: string;
}

export interface Method {
  slug: string;
  path: string;
  metaTitle: string;
  metaDescription: string;
  kicker: string;
  /** שם הכלי כפי שמופיע בספר. */
  term: string;
  h1: string;
  /** הגדרה קצרה, ניתנת לציטוט — מיד אחרי ה-H1. */
  lead: string;
  /** תיאור למטא-נתוני DefinedTerm (משפט הגדרה אחד). */
  definition: string;
  intro: string[];
  sections: MethodSection[];
  /** הכלי המקביל בעמוד הספר (עוגן #tool-<id>). id תואם ל-ToolItem.id. */
  bookTool: { id: string; name: string };
  /**
   * תחנה לטעימה הממוקדת (`/preview?tool=&station=`). הערך הוא ה-station הקנוני
   * של הכלי כפי שמוגדר ב-book.ts (ToolItem.station) — מפתח תקף ב-stations. אין
   * המצאת ערכי station.
   */
  previewStation: "before-relationship" | "starting-again" | "inside-relationship";
  askStation?: AskStationId;
  /** מדריכי /guide/* שמיישמים את המושג — קישור הדדי. */
  relatedGuides: MethodLink[];
  /** „מפת סינון” אינטראקטיבית (אופציונלי) — קיימת רק ל„קו אדום מול גמישות”. */
  filterMap?: FilterMap;
  datePublished: string;
}

