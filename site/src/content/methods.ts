/**
 * עמודי-מושג (/method/*) — ההגדרה הקנונית של הכלים המקוריים של „מדייטים לאהבה”.
 * כל הגדרה נגזרת אך ורק מהמקור הקיים (src/content/book.ts, tools) — אין המצאת
 * מושגים או הגדרות. עמוד-המושג הוא ה„שם-העצם” (מהו הכלי); עמודי /guide/* הם
 * ה„פועל” (איך מיישמים אותו במצב מסוים), ומקושרים הדדית. כל עמוד נושא canonical
 * עצמי, וסכימת DefinedTerm המחוברת לישות הספר.
 *
 * חשוב: משתמשים רק בכלים המאומתים בספר. שמות שלא קיימים במקור (למשל „מפת הערכים”,
 * „שאלת הדגלים”, „הסכם ההתחלה”, „הסכמה רגשית”) — אינם בשימוש כאן.
 */

