export interface GuideSection {
  /** H2 */
  heading: string;
  paragraphs: string[];
  /** רשימת נקודות עם כותרות-משנה (H3) — אופציונלי. */
  points?: { title: string; body: string }[];
}

export interface GuideFramework {
  kicker: string;
  title: string;
  intro?: string;
  items: string[];
  note?: string;
}

export interface GuideLink {
  href: string;
  label: string;
  sub?: string;
}

export interface Guide {
  slug: string;
  /** נתיב מלא, למשל /guide/finding-a-relationship. */
  path: string;
  /** מטא-כותרת ללא „| מדייטים לאהבה” (התבנית מוסיפה אותה). */
  metaTitle: string;
  metaDescription: string;
  kicker: string;
  h1: string;
  /** תשובה קצרה וישירה לחשש של הקורא — מיד אחרי ה-H1. */
  lead: string;
  intro: string[];
  sections: GuideSection[];
  framework?: GuideFramework;
  /** שורת-הבהרה (למאמר הספקות) — כיוון, לא אבחון. */
  disclaimer?: string;
  /** תחנת-עוזר ל„שאל את הספר”. undefined → העוזר ישאל „איפה אתם?”. */
  askStation?: AskStationId;
  /** עמוד-האם (hub) של האשכול. */
  hub: GuideLink;
  /** קישור-הקשר נוסף (למשל /building-relationship / /inside-relationship). */
  secondary?: GuideLink;
  /** קישורים למאמרים אחרים באשכול — רק היכן שהקורא באמת יֵהנה. */
  related: GuideLink[];
  /**
   * כלי מאומת מהספר שהמדריך נשען עליו (עוגן `#tool-<id>` ב-/book). מאפשר קישור
   * פנימי מהמדריך אל הכלי בעמוד הספר. `id` חייב להתאים ל-`ToolItem.id` ב-book.ts.
   */
  bookTool?: { id: string; name: string };
  /** קישור לעמוד-מושג ב-/method/* (המושג המקורי שהמדריך מיישם). */
  method?: GuideLink;
  /** ISO — מאמר מתוארך אמיתי (פורסם עכשיו). */
  datePublished: string;
}

