import Image from "next/image";

import { cn } from "@/lib/utils";

/**
 * סמל המותג — קובץ הלוגו שסופק ע"י המחבר.
 *
 * **מקור-אמת יחיד.** הרכיב הזה הוא המקום *היחיד* שבו נתיב הלוגו מופיע. שישה
 * משטחים צורכים אותו (הדר, מגירת המובייל, פוטר, סקשן התזה, ‎/en ו-‎/love),
 * ולכן החלפת הלוגו היא שינוי בקובץ אחד — לא שכפול בשישה.
 *
 * **הנכס אינו נגזר ואינו נערך.** ה-PNG המקורי (1600×1600, RGBA עם שקיפות)
 * מוגש כמות שהוא: אין חיתוך, אין מתיחה, אין צביעה מחדש. `object-contain`
 * שומר על יחס-הצדדים בכל תיבה, גם אם בעתיד תיקבע תיבה שאינה ריבועית.
 *
 * **צבע.** הגרסה הקודמת הייתה SVG מוטבע שירש `currentColor`, ולכן מחלקות
 * `text-*` שבאתרי-הקריאה השפיעו עליו. לוגו-תמונה נושא את צבעו שלו ואסור
 * לצבוע אותו מחדש, ולכן המחלקות האלה אינן משפיעות עליו יותר. הן נשארו
 * באתרי-הקריאה בלי לגעת בהן — הן חסרות-השפעה, והסרתן היא שינוי שאינו נדרש
 * להחלפת הלוגו.
 *
 * **נגישות.** הסמל מסומן דקורטיבי (`alt=""` + `aria-hidden`) בדיוק כפי שהיה
 * ב-SVG הקודם. בכל ששת המקומות שם המותג כבר נמסר לטכנולוגיה מסייעת בסמוך —
 * ב-`aria-label` של הקישור בהדר, ובטקסט הנראה שלצדו במגירה ובפוטר. alt
 * שאינו ריק היה גורם להכרזה כפולה של אותו שם.
 */

/** הנכס שסופק ואושר ע"י המחבר. אין עותק שני שלו במאגר. */
const LOGO_SRC = "/images/original_heart_terracotta_final.png";

export function BrandMark({
  className,
  withRing = false,
}: {
  className?: string;
  /** עיגול-רקע מאחורי הסמל. נשאר בפוטר; הוסר מההדר וממגירת המובייל. */
  withRing?: boolean;
}) {
  return (
    <span
      className={cn(
        "relative inline-flex shrink-0 items-center justify-center",
        withRing ? "rounded-full bg-brand-muted" : null,
        className,
      )}
    >
      <Image
        src={LOGO_SRC}
        alt=""
        aria-hidden="true"
        // המידות המוצהרות קובעות את יחס-הצדדים ואת ה-srcset; הגודל בפועל
        // נקבע ע"י התיבה (`h-9 w-9` בהדר), כמו שהיה ב-SVG.
        width={40}
        height={40}
        // ברירת המחדל של next/image היא `loading="lazy"`, וזו ההגדרה הלא-נכונה
        // בדיוק כאן: הסמל יושב בהדר הדביק, כלומר בתוך המסך הראשון של *כל* עמוד,
        // וטעינה נדחית רק הייתה גורמת לו להופיע רגע אחרי שאר ההדר. הגרסה
        // הקודמת הייתה SVG מוטבע שנצבע מיד. אותו URL בכל אתרי-הקריאה, ולכן
        // מדובר בהקדמה אחת (~2KB) ולא באחת לכל מופע.
        priority
        className="h-full w-full object-contain"
      />
    </span>
  );
}
