/**
 * רשימת שאלות-בדיקה בתוך פרק של עמוד-אב.
 *
 * ── למה זו רשימה ולא פסקה ─────────────────────────────────────────────────
 * בגוף המקטע שלוש השאלות ישבו בתוך משפט אחד, זו אחרי זו, מופרדות בסימני
 * שאלה בלבד. זה נקרא נכון למי שקורא כל מילה, ונעלם לגמרי למי שסורק: שלוש
 * בדיקות שאפשר לעשות בפועל נראו כמו סוף של פסקה. הן פריטים נפרדים ושווי-משקל
 * מטבעם, ולכן `ul`/`li` אינם עיצוב כאן אלא הסמנטיקה הנכונה — וקורא מסך שעובר
 * ברשימה שומע עכשיו „שלושה פריטים” במקום משפט אחד ארוך.
 *
 * ── ולמה לא כרטיסים ──────────────────────────────────────────────────────
 * כרטיס אומר „יחידת תוכן”, ואלה שאלות באורך שורה. הסימון הוא הנקודה שכבר
 * מסמנת בעמוד הזה כל מקטע ואת ציטוט-הסיום, בגודל שמתאים לפריט ברשימה. זו
 * אותה שפה, לא עוד אחת.
 *
 * `list-none` + נקודה משלנו ולא `list-disc`: תבליט דפדפן בברירת מחדל נוחת
 * במרחק אחר ב-RTL ואינו נושא את צבע המותג.
 */
export function SectionQuestions({ items }: { items: readonly string[] }) {
  return (
    <ul className="mt-5 list-none space-y-3.5 ps-0">
      {items.map((q) => (
        <li key={q} className="flex items-start gap-3">
          <span
            aria-hidden="true"
            className="mt-[0.62rem] h-[5px] w-[5px] shrink-0 rounded-full bg-brand"
          />
          <span className="max-w-[58ch] text-[1.06rem] leading-[1.75] text-foreground">{q}</span>
        </li>
      ))}
    </ul>
  );
}
